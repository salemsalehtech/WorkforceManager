namespace WorkforceManager.Core.Models
{
    /// <summary>
    /// تحويل القطع ليوميات — القاعدة الحسابية الوحيدة في البرنامج كله.
    ///
    /// ليه ملف لوحده: الرقم ده بيتضرب في سعر اليومية وبيطلع أجر العامل،
    /// فأي نسخة تانية منه معناها شاشتين بيقولوا رقمين مختلفين لنفس الشغل.
    /// وده اللي كان بيحصل فعلاً: معاينة الحفظ كانت بتجمع الكسور الكاملة
    /// وتقرّب مرة واحدة في الآخر، وباقي البرنامج بيقرّب كل سجل لوحده
    /// وبعدين يجمع. النتيجة إن المعاينة تقول 1.00 يومية والكشف الأسبوعي
    /// يقول 0.99 لنفس اليوم بالظبط.
    ///
    /// القاعدة المعتمدة: **قرّب كل سجل لوحده لخانتين عشريتين**، لأن السجل
    /// هو وحدة الشغل اللي العامل بيتحاسب عليها وبتظهر له في كشفه — والمجموع
    /// لازم يساوي اللي هو شايفه سطر سطر.
    /// </summary>
    public static class WorkdayMath
    {
        /// <summary>خانتين عشريتين — أدق من كده مالوش معنى في كشف أجور</summary>
        public const int Decimals = 2;

        /// <summary>
        /// يوميات سجل واحد = قطعه ÷ يوميته، مقرّبة لخانتين.
        ///
        /// يومية بصفر بترجع صفر بدل ما ترمي: التحقق بيمنعها عند الإدخال،
        /// بس بيانات قديمة أو متبوّظة ميصحش تكسر كشف الأجور كله.
        /// </summary>
        public static decimal FromPieces(int pieceCount, int piecesPerWorkday) =>
            piecesPerWorkday == 0
                ? 0m
                : Math.Round((decimal)pieceCount / piecesPerWorkday, Decimals);
    }
}
