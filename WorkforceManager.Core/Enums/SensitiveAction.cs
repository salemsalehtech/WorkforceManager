namespace WorkforceManager.Core.Enums
{
    /// <summary>
    /// العمليات اللي لازم تعدّي على بوابة كلمة سر العمليات قبل ما تتنفّذ.
    ///
    /// القايمة دي مقصود إنها **صريحة ومحصورة**: العمليات اللي بتمسح شغل
    /// أو بتلمس فلوس. تسجيل الإنتاج نفسه **مش** هنا عن قصد — هو الشغل
    /// اليومي المتكرر، وكلمة سر على كل حفظة معناها إن المستخدم هيدوّر
    /// على طريقة يلفّ بيها حوالين النظام.
    ///
    /// الحضور دخل القايمة رغم إنه شغل يومي، والفرق إنه بيتحفظ **دفعة
    /// واحدة لكل القسم** (RecordAttendanceBatchAsync): كلمة سر واحدة في
    /// اليوم، مش واحدة لكل عامل. وهو بيولّد جزاءات غياب تلقائية بتنقص
    /// من الأجر، فهو فعليًا عملية بتلمس فلوس.
    ///
    /// إضافة عملية جديدة = بند جديد هنا + نداء واحد للبوابة. مفيش شاشة
    /// بتتحقق من كلمة السر بنفسها.
    /// </summary>
    public enum SensitiveAction
    {
        /// <summary>حذف عامل</summary>
        DeleteWorker = 1,

        /// <summary>حذف منتج</summary>
        DeleteProduct = 2,

        /// <summary>حذف مرحلة إنتاج</summary>
        DeleteStage = 3,

        /// <summary>حذف سجل إنتاج أو يوم إنتاج كامل</summary>
        DeleteProduction = 4,

        /// <summary>تعديل سعر يومية العامل</summary>
        EditWorkerWage = 5,

        /// <summary>تعديل عدد قطع سجل إنتاج محفوظ</summary>
        EditProductionPieces = 6,

        /// <summary>حفظ أو تعديل جزاء</summary>
        SavePenalty = 7,

        /// <summary>تسجيل أو تعديل سلفة/حافز</summary>
        SaveWageAdjustment = 8,

        /// <summary>حفظ حضور اليوم (دفعة واحدة لكل القسم)</summary>
        SaveAttendance = 9,

        /// <summary>
        /// تسجيل إنتاج (رحلة منتج أو سجل مفرد).
        ///
        /// الإنتاج هو اللي اليوميات بتتحسب منه، واليوميات هي الأجر —
        /// فتسجيل إنتاج غلط بيتحوّل لفلوس غلط زي أي عملية تانية في
        /// القايمة دي.
        /// </summary>
        RecordProduction = 10,

        // 11 (CloseProductionDay) اتشالت خالص لما ميزة قفل إنتاج اليوم
        // (DayClosureService) اتلغت بالكامل — القيمة دي عمرها ما كانت
        // متخزّنة في أي صف قاعدة بيانات (بتتبعت كباراميتر وقت التشغيل بس
        // لـ VerifyAsync)، فمفيش قيد تاريخي يمنع حذفها خالص، على عكس
        // ActivityEventType.ProductionDayClosed/Reopened اللي **متخزّنين**
        // في صفوف سجل عمليات حقيقية وفضلوا في enum بتاعهم عن قصد.

        /// <summary>
        /// تسجيل هالك — نفس منطق RecordProduction: الهالك بيتخصم من
        /// الإنتاج التام وبيأثر على تقارير حقيقية، فتسجيله غلط بيلخبط
        /// أرقام زي أي عملية تانية في القايمة دي.
        ///
        /// **ملحوظة (توقيع نهاية اليوم)**: من 10, 6, 7, 9, 4 و12 اتشالوا
        /// من هنا فعليًا (Tier B) — الشغل اليومي المتكرر بقى بدون باسورد
        /// فوري، وبيتغطى بتوقيع نهاية اليوم بدل كده. القيم فضلت في الـ enum
        /// لمجرد إن مفيش داعي نعيد ترقيم أي حاجة (مش لأنها متخزّنة — القيمة
        /// دي زي CloseProductionDay مش بتتخزّن في أي صف، بس مفيش سبب حقيقي
        /// يستاهل حذفها كمان). مفيش نداء VerifyAsync ليها في الكود دلوقتي.
        /// شوف DailyOperationsSignOffService.
        /// </summary>
        RecordScrap = 12,

        /// <summary>
        /// توقيع نهاية اليوم — البوابة الوحيدة الباقية للشغل اليومي
        /// المتكرر (Tier B) بعد ما اتشالت منه الباسوردات الفورية. نفس
        /// البوابة بتتستخدم للحاق يوم فات ما اتوقّعش (بدء التشغيل).
        /// </summary>
        DailySignOff = 13,

        /// <summary>
        /// تغيير إعدادات النظام — فجوة كانت موجودة (الشاشة مفيهاش حماية
        /// خالص غير تغيير باسورد العمليات نفسه)، اتقفلت هنا.
        /// </summary>
        ChangeSettings = 14
    }
}
