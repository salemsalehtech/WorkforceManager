namespace WorkforceManager.Core.Enums
{
    /// <summary>
    /// مصدر الجزاء: مسجّل بإيد المستخدم ولا اتولّد تلقائيًا من قاعدة في
    /// النظام. الفرق مهم عشان البرنامج **ميلمسش أبدًا** جزاء كتبه
    /// المستخدم بنفسه — التعديل والحذف التلقائي بيشتغلوا بس على
    /// الجزاءات اللي هو اللي ولّدها.
    /// </summary>
    public enum PenaltySource
    {
        /// <summary>
        /// جزاء سجّله المستخدم يدويًا من تبويب الجزاءات.
        /// القيمة صفر عن قصد: كل الجزاءات المسجّلة قبل إضافة الحقل ده
        /// بتاخد الصفر تلقائيًا، يعني بتفضل "يدوية" ومحميّة زي ما هي.
        /// </summary>
        Manual = 0,

        /// <summary>
        /// جزاء اتولّد تلقائيًا بسبب غياب بدون إذن (نص يومية).
        /// بيتولّد وبيتشال لوحده مع تغيير حالة الحضور — راجع
        /// AttendanceAutomationService.
        /// </summary>
        AutoAbsence = 1
    }
}
