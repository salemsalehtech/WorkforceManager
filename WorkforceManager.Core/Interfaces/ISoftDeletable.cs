using System;

namespace WorkforceManager.Core.Interfaces
{
    /// <summary>
    /// الكيان ده بيتشال بتغيير حالة مش بحذف فعلي من الداتابيز.
    ///
    /// ليه: الصف المحذوف ممكن يكون مربوط بسجلات تاريخية (إنتاج، أجور،
    /// جزاءات). لو اتشال فعليًا، السجلات دي بتبقى بتشاور على العدم —
    /// وكشف أجور قديم بيتحوّل لأرقام من غير أسماء.
    ///
    /// أي كيان بيطبّق الواجهة دي بيتفلتر تلقائيًا من كل الاستعلامات
    /// العادية (فلتر عام في AppDbContext)، فمفيش شاشة محتاجة تفتكر
    /// تكتب "&amp;&amp; !IsDeleted" — النسيان ده هو اللي بيسرّب صفوف محذوفة
    /// للواجهة.
    /// </summary>
    public interface ISoftDeletable
    {
        /// <summary>اتشال؟ الفلتر العام بيعتمد على ده</summary>
        bool IsDeleted { get; set; }

        /// <summary>لحظة الحذف (null لو لسه موجود)</summary>
        DateTime? DeletedAt { get; set; }

        /// <summary>اسم المستخدم اللي حذف — بيتخزن كنص مش كمفتاح أجنبي</summary>
        string? DeletedBy { get; set; }

        /// <summary>سبب الحذف اللي كتبه المستخدم</summary>
        string? DeletionReason { get; set; }

        /// <summary>
        /// اسم الكيان وقت الحذف بالظبط.
        ///
        /// السجلات التاريخية بتعرض الاسم ده مش الاسم الحالي: لو العامل
        /// اتشال وبعدين حد سمّى عامل جديد بنفس الاسم، تقرير قديم لازم
        /// يفضل بيقول الاسم اللي كان وقتها.
        /// </summary>
        string? DeletedName { get; set; }
    }
}
