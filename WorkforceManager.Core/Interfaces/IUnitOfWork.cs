namespace WorkforceManager.Core.Interfaces
{
    /// <summary>
    /// معاملة كتابة واحدة: يا كل التعديلات تتحفظ يا مفيش حاجة خالص.
    /// بتتقفل بـ Dispose — ولو اتقفلت من غير Commit بيحصل تراجع تلقائي
    /// (فمفيش طريق يسيب نص عملية متحفوظة).
    /// </summary>
    public interface IDataTransaction : IAsyncDisposable
    {
        Task CommitAsync();
    }

    /// <summary>
    /// بيفتح معاملة كتابة على نفس اتصال الـ Repositories في الـ Scope الحالي.
    ///
    /// موجودة عشان قاعدة "العامل ميشتغلش على أكتر من مرحلة في نفس اليوم"
    /// لازم تتحقق وتتحفظ **كوحدة واحدة**: من غير كده، لو نسختين من
    /// البرنامج بيسجلوا نفس العامل في نفس اللحظة، الاتنين يقروا "مفيش
    /// تعارض" ويكتبوا — والقاعدة تتخطى من غير ما حد ياخد باله.
    /// المعاملة هنا بتاخد قفل الكتابة **من أول لحظة** (مش عند أول كتابة)،
    /// فالقراءة اللي بيتبني عليها القرار بتكون محمية زي الكتابة بالظبط.
    ///
    /// الواجهة في Core (من غير أي أثر لـ EF Core) عشان تفضل طبقة الأعمال
    /// مستقلة عن تقنية التخزين زي باقي الـ Repositories.
    /// </summary>
    public interface IUnitOfWork
    {
        Task<IDataTransaction> BeginWriteTransactionAsync();
    }
}
